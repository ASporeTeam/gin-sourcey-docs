def sh(cmd, cwd=None, env=None):
    e = dict(os.environ)
    e["PATH"] = NODE_DIR + ":" + GO_DIR + ":" + e.get("PATH", "")
    if env:
        e.update(env)
    p = subprocess.run(cmd, capture_output=True, text=True, cwd=cwd, env=e,
                       timeout=300)
    return (p.stdout or "").strip(), (p.stderr or "").strip(), p.returncode


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fetch(url, timeout=45):
    req = urllib.request.Request(url, headers={
        "User-Agent": "Mozilla/5.0 (X11; Linux x86_64) spore-agent/1.0",
        "Accept": "*/*"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.status, r.read().decode("utf-8", "replace")
    except Exception as exc:
        return 0, "error: %s" % exc


